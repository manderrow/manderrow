#!/usr/bin/env python3
"""Lints the QML with qmllint.

The type information of the types the app defines in Rust is generated by `just gen` or the
build, which `just lint` runs `just gen` for. The QML itself is linted as it is in `src/qml`:
qmllint is pointed at a copy of the exported QML module whose files are the sources, rather than
the copies of them in the module, which are only as new as the last generation. Without file
arguments, every QML file is linted, and any warning fails.

Usage: [QMAKE=<qmake>] lint-qml.py [qmllint options...] [files...]
"""

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def qmake_query(key: str) -> Path:
    # the same qmake as build.rs
    candidates = [os.environ["QMAKE"]] if "QMAKE" in os.environ else ["qmake6", "qmake"]
    for qmake in candidates:
        try:
            output = subprocess.run([qmake, "-query", key], capture_output=True, text=True)
        except FileNotFoundError:
            continue
        if output.returncode == 0:
            return Path(output.stdout.strip())
    sys.exit("Unable to locate Qt. Set the QMAKE environment variable to the path of qmake.")


def write_lint_module(exported: Path, module: Path):
    """Writes a QML module like the exported one at `exported`, but whose files are the sources."""
    module.mkdir(parents=True, exist_ok=True)
    (module / "plugin.qmltypes").write_bytes((exported / "plugin.qmltypes").read_bytes())
    # the module's files are listed relative to its qmldir, as they are relative to the crate
    to_root = Path(os.path.relpath(ROOT, module)).as_posix()
    lines = []
    for line in (exported / "qmldir").read_text().splitlines():
        words = line.split()
        if words and words[0] == "prefer":
            # it would send qmllint back to the exported module
            continue
        if words and words[-1].endswith(".qml"):
            words[-1] = f"{to_root}/{words[-1]}"
        lines.append(" ".join(words))
    (module / "qmldir").write_text("\n".join(lines) + "\n")


def main():
    # where cxx-qt exports the QML module, as the build script finds it
    target = Path(os.environ.get("CARGO_TARGET_DIR", ROOT / "target"))
    exported = target / "cxxqt" / "qml_modules" / "Manderrow"
    if not (exported / "qmldir").exists():
        sys.exit(f"No QML module in {exported}. Run `just gen` first.")
    modules = target / "qmllint"
    write_lint_module(exported, modules / "Manderrow")

    args = sys.argv[1:]
    if not any(arg.endswith(".qml") for arg in args):
        args = ["--max-warnings", "0"] + args
        args += sorted(str(path) for path in (ROOT / "src" / "qml").rglob("*.qml"))

    qmllint = qmake_query("QT_HOST_BINS") / "qmllint"
    sys.exit(subprocess.run([str(qmllint), "-I", str(modules)] + args).returncode)


if __name__ == "__main__":
    main()
